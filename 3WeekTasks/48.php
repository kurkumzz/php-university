<?php
// Задача 48. Двойной факториал: 1*3*...*N (N нечетное) или 2*4*...*N (N четное)
echo "Введите N (> 0): "; $n = (int)trim(fgets(STDIN));
if ($n <= 0) { echo "Ошибка: N должно быть > 0\n"; exit; }
$f = 1.0;
for ($i = ($n % 2 == 1 ? 1 : 2); $i <= $n; $i += 2) {
    $f *= $i;
}
echo "N!! = " . sprintf("%.1f", $f) . "\n";
