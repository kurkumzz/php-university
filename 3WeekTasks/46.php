<?php
// Задача 46. Наибольшее N, при котором 1 + 1/2 + ... + 1/N < A, и эта сумма
echo "Введите A (> 1): "; $a = (float)trim(fgets(STDIN));
if ($a <= 1) { echo "Ошибка: A должно быть > 1\n"; exit; }
$n = 1;
$s = 1;
while ($s + 1 / ($n + 1) < $a) {
    $n++;
    $s += 1 / $n;
}
echo "N = $n\nСумма = $s\n";
