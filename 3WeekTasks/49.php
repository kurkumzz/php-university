<?php
// Задача 49. 2 + 1/2! + 1/3! + ... + 1/N!  (приближение e)
// Первое слагаемое 2 = 1 + 1/1!, поэтому начинаем с i = 2
echo "Введите N (> 0): "; $n = (int)trim(fgets(STDIN));
if ($n <= 0) { echo "Ошибка: N должно быть > 0\n"; exit; }
$s = 2.0;
$f = 1.0;
for ($i = 2; $i <= $n; $i++) {
    $f *= $i;
    $s += 1 / $f;
}
echo "Сумма = $s\n";
echo "exp(1) = " . exp(1) . "\n";
